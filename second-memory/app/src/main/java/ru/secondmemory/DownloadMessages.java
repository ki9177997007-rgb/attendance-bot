package ru.secondmemory;
final class DownloadMessages {
 static String error(int code){
  if(code>=400&&code<=599)return "Сервер загрузки ответил HTTP "+code+". Повтори загрузку или скачай через браузер и выбери файл модели.";
  switch(code){case 1001:return "Не удалось записать файл. Проверь свободное место и повтори загрузку.";
   case 1004:return "Соединение оборвалось при загрузке. Повтори загрузку или используй браузер.";
   case 1005:return "Слишком много перенаправлений сервера. Скачай через браузер и выбери файл модели.";
   case 1006:return "Не хватает места: освободи не менее 1,5 ГБ и повтори загрузку.";
   case 1007:return "Хранилище телефона недоступно. Повтори загрузку после его подключения.";
   case 1008:return "Не удалось продолжить загрузку. Нажми «Скачать / повторить загрузку».";
   case 1009:return "Остался незавершённый файл. Нажми «Скачать / повторить загрузку».";
   default:return "Загрузка не завершена, код "+code+". Повтори загрузку или используй браузер.";
  }
 }
 static String paused(int code){switch(code){case 1:return "Сеть прервалась; Android ждёт повторной попытки.";case 2:return "Ожидание доступной сети. Проверь интернет; загрузка в роуминге отключена.";case 3:return "Ожидание Wi-Fi. Для мобильной сети нажми повтор загрузки → Любая сеть.";default:return "Загрузка приостановлена Android. Проверь подключение или повтори загрузку.";}}
}
